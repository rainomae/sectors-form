// Generates src/main/resources/db/migration/V2__seed_sectors.sql from the original index.html.
//
// Every <option> becomes one sector row: the option value is the id, the number of leading
// &nbsp; entities (4 per level) gives the depth from which parent_id is derived, and the position
// in the list becomes sort_order. Labels are trimmed and HTML entities are decoded.
//
// Run from the backend folder:  node tools/generate-sector-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const input = resolve(root, '../docs/original/index.html');
const output = resolve(root, 'src/main/resources/db/migration/V2__seed_sectors.sql');

const html = readFileSync(input, 'utf8');
const optionPattern = /<option value="(\d+)">((?:&nbsp;)*)(.*?)<\/option>/g;
const indentPerLevel = 4;

const rows = [];
const lastIdAtLevel = [];
let match;
while ((match = optionPattern.exec(html)) !== null) {
  const id = Number(match[1]);
  const indent = match[2].length / '&nbsp;'.length;
  if (indent % indentPerLevel !== 0) {
    throw new Error(`Unexpected indentation (${indent} &nbsp;) for option ${id}`);
  }
  const level = indent / indentPerLevel;
  const name = match[3].replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
  const parentId = level === 0 ? null : lastIdAtLevel[level - 1];
  if (level > 0 && parentId === undefined) {
    throw new Error(`Option ${id} has no parent at level ${level - 1}`);
  }
  lastIdAtLevel[level] = id;
  lastIdAtLevel.length = level + 1;
  rows.push({ id, name, parentId, sortOrder: rows.length + 1 });
}

if (new Set(rows.map((row) => row.id)).size !== rows.length) {
  throw new Error('Duplicate option values in the source');
}

const sqlString = (value) => `'${value.replace(/'/g, "''")}'`;
const values = rows
  .map((row) => `    (${row.id}, ${sqlString(row.name)}, ${row.parentId ?? 'NULL'}, ${row.sortOrder})`)
  .join(',\n');

const sql = `-- Seed data for the sector reference table.
-- GENERATED by tools/generate-sector-seed.mjs from docs/original/index.html; do not edit by hand.
-- id is the original <option value>, parent_id is derived from the &nbsp; indentation depth and
-- sort_order preserves the original display order.

INSERT INTO sector (id, name, parent_id, sort_order) VALUES
${values};
`;

writeFileSync(output, sql, 'utf8');
console.log(`Wrote ${rows.length} sectors to ${output}`);
